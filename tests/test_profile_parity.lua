local profiles, store, defaults = require('core.profiles'), require('core.store'), require('ui.defaults');
local p = profiles.new(MOCK_INSTALL_PATH .. '/config/addons/vantage');
local s = defaults.make();
s.panels.self_buffs.labels[33] = 'Haste';
s.panels.party.members[12345] = true;
assert(p:save_new('  Healer  ', s));
assert(store.read(p.path).Healer.panels.party.members == nil, 'Named profiles must not save character-specific entity selections.');
assert(p:source('Missing', s).name == 'Missing' and not p:source('Missing', s).exists);
assert(p:source('Healer', s).exists and not p:source('Healer', s).modified);
assert(p:source('  healer  ', s).name == 'Healer');
assert(not p:save_new('healer', s) and not p:save_new('(none)', s));
assert(not p:overwrite('Healer', s), 'Overwrite needs the displayed source token.');
assert(p:link(s, 3, 'healer') and s.job_profiles['3'] == 'Healer');
s.active_profile = 'Healer';
s.window.tab, s.watch_ids, s.shared_scope = 'Help', {77}, 'presentation';
assert(not p:status(s).modified, 'Navigation, sharing mode and live entity watch state are personal.');
s.style.font_size = 22;
assert(p:status(s).modified);
local original = p:source('Healer').token;
assert(p:overwrite('Healer', s, original));
assert(not p:status(s).modified and p:recovery().kind == 'overwrite');
local peer = profiles.new(p.folder);
assert(peer:save_new('Unrelated', defaults.make()));
assert(p:recover(s));
assert(p:source('Healer').token == original and p:source('Unrelated').exists);
assert(p:status(s).modified, 'Recovering a saved source must not discard unsaved settings.');
assert(not p:recover(s));
local stale = p:source('Healer').token;
local external = defaults.make(); external.style.font_size = 25;
assert(peer:overwrite('Healer', external, stale));
assert(not p:overwrite('Healer', s, stale));
assert(not p:delete('Healer', stale, s));
assert(not p:rename('Healer', 'Mage', s, stale));
assert(s.job_profiles['3'] == 'Healer' and s.active_profile == 'Healer');
assert(not p:rename('Healer', 'unrelated', s));
local current = p:source('Healer').token;
MOCK.file_replace_error = true;
assert(not p:rename('Healer', 'Mage', s, current));
assert(s.job_profiles['3'] == 'Healer' and s.active_profile == 'Healer');
MOCK.file_replace_error = false;
assert(p:rename('Healer', 'Mage', s, current));
assert(s.job_profiles['3'] == 'Mage' and s.active_profile == 'Mage');
assert(p:source('Mage').token == current and not p:source('Healer').exists);
s.job_profiles['3'] = 'Unrelated';
assert(p:recover(s));
assert(s.job_profiles['3'] == 'Unrelated' and s.active_profile == 'Healer', 'Recovery preserves later job-link choices.');
assert(p:rename('Healer', 'HEALER', s));
assert(p:source('HEALER').exists and p:recover(s));
assert(p:source('Healer').exists);
p:set_owner('1001:Tester');
assert(p:link(s, 3, 'Healer') and p:delete('Healer', nil, s));
s = defaults.tidy(defaults.copy(s));
s.style.font_size = 26;
assert(p:recover(s) and s.job_profiles['3'] == 'Healer', 'Same-character settings replacements must preserve recovery ownership.');
assert(p:delete('Healer', nil, s));
p:set_owner('1002:Other');
local switched = defaults.make();
assert(p:recover(switched) and not switched.job_profiles['3'], 'Recovery cannot attach another character job links.');
p:set_owner(nil);
s.active_profile = 'Healer';
assert(p:link(s, 3, 'Healer'));
assert(p:delete('Healer', p:source('Healer').token, s));
assert(not s.job_profiles['3'] and s.active_profile == '');
assert(peer:save_new('healer', external));
assert(not p:recover(s), 'External case-insensitive name reuse must block recovery.');
assert(p:recovery().kind == 'delete');
assert(peer:delete('healer'));
assert(p:recover(s) and s.job_profiles['3'] == 'Healer' and s.active_profile == 'Healer');
assert(p:delete('Healer', nil, s));
local other = defaults.make(); other.job_profiles['3'] = 'Unrelated';
assert(p:recover(other));
assert(other.job_profiles['3'] == 'Unrelated' and other.active_profile == '' and s.job_profiles['3'] == nil);
assert(p:overwrite('Healer', s, p:source('Healer').token));
assert(peer:overwrite('Healer', external, peer:source('Healer').token));
assert(not p:recover(s) and p:source('Healer').token == peer:source('Healer').token);

local stored = profiles.capture(defaults.make());
stored.style.font, stored.window_style.font_size = 'Bahnschrift', 21;
stored.panels.party.members = {[12345] = true};
local database = assert(store.read(p.path)); database.Stored = stored; assert(store.write(p.path, database));
local into = defaults.make();
into.window_style.font_size = 28;
into.panels.party.members = {[67890] = true};
assert(p:load('Stored', into));
assert(into.style.font == 'Bahnschrift' and into.window_style.font_size == 21,
    'A profile brings its own font and window text size.');
assert(not p:source('Stored', into).modified);
assert(into.panels.party.members[67890] and not into.panels.party.members[12345], 'Named profiles cannot restore obsolete entity selections.');

-- Placement and full presentation share only the explicitly chosen scope.
local source, receiver = defaults.make(), defaults.make();
source.panels.self_buffs.x, source.panels.self_buffs.width = 500, 450;
source.panels.self_buffs.auto_width, source.panels.self_buffs.anchor.to, source.panels.self_buffs.anchor.element = true, 'element', 'target';
source.panels.self_buffs.anchor.offset = 89;
source.panels.self_buffs.row_height, source.panels.self_buffs.enabled = 40, false;
source.panels.self_buffs.members, source.panels.self_buffs.locked = {[55] = true}, false;
source.style.font_size, source.window_style.font_size = 23, 24;
source.window.tab, source.watch_ids, source.job_profiles['1'], source.tracking.stale_seconds = 'Help', {123}, 'Healer', 300;
source.alerts.notice_width, source.alerts.muted, source.alerts.rules = 555, true, { defaults.rule('source') };
receiver.panels.self_buffs.members = {[66] = true};
receiver.alerts.rules = {defaults.rule('personal')};
assert(p:save_layout(source, 'placement') and p:load_layout(receiver, 'placement'));
assert(receiver.panels.self_buffs.x == 500 and receiver.panels.self_buffs.auto_width and receiver.panels.self_buffs.anchor.element == 'target');
assert(receiver.panels.self_buffs.anchor.offset == 89);
assert(receiver.panels.self_buffs.row_height == 0 and receiver.panels.self_buffs.enabled and receiver.style.font_size == 16);
assert(receiver.panels.self_buffs.locked and receiver.panels.self_buffs.members[66]);
assert(p:save_layout(source, 'presentation'));
local raw = store.read(p.layout_path);
assert(raw.presentation.panels.self_buffs.members == nil and raw.presentation.panels.self_buffs.locked == nil);
assert(raw.presentation.alerts.rules == nil and raw.presentation.window == nil and raw.presentation.tracking == nil);
assert(p:load_layout(receiver, 'presentation'));
assert(receiver.style.font_size == 23 and receiver.window_style.font_size == 24 and not receiver.panels.self_buffs.enabled);
assert(receiver.panels.self_buffs.row_height == 40 and receiver.panels.self_buffs.members[66] and not receiver.panels.self_buffs.members[55]);
assert(receiver.panels.self_buffs.locked and receiver.window.tab == 'Home' and #receiver.watch_ids == 0 and not receiver.job_profiles['1']);
assert(receiver.tracking.stale_seconds == 180 and receiver.alerts.rules[1].id == 'personal' and not receiver.alerts.muted);
assert(receiver.alerts.notice_width == 555 and receiver.shared_scope == 'placement');
local placement_only = defaults.make();
assert(p:load_layout(placement_only, 'placement'));
assert(placement_only.panels.self_buffs.x == 500 and placement_only.style.font_size == 16 and placement_only.panels.self_buffs.enabled);
assert(p:save_layout(source, 'placement') and p:load_layout(receiver, 'presentation'));
assert(receiver.style.font_size == 23, 'Placement documents must not reset presentation settings.');
assert(not p:save_layout(source, 'all') and not p:load_layout(receiver, 'all'));
local file = assert(io.open(p.path, 'wb')); file:write('invalid JSON'); file:close();
assert(not p:save_new('Untouched', s) and not p:rename('Healer', 'Mage', s) and not p:recover(s));
assert(p:source('Healer', s).name == 'Healer');
file = assert(io.open(p.path, 'rb')); assert(file:read('*a') == 'invalid JSON'); file:close();
return true;
