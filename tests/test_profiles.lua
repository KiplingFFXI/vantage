local profiles = require('core.profiles');
local store = require('core.store');
local defaults = require('ui.defaults');
local p = profiles.new(MOCK_INSTALL_PATH .. '/config/addons/vantage');
local settings = defaults.make();
settings.style.font_size = 21;
settings.panels.self_buffs.x = 301;
settings.job_profiles['1'] = 'Private';
settings.window.x = 999;
settings.shared_layout, settings.preview = true, true;
settings.watch_ids = {16781313};
assert(p:save_new('Healer', settings));
assert(p:save_new('Tank', settings));
assert(#p:list() == 2 and p:list()[1] == 'Healer');
assert(not p:save_new('', settings));
assert(not p:save_new('None', settings));
assert(not p:save_new('Hidden##id', settings));
local other = defaults.make();
other.window.x = 88;
other.job_profiles['2'] = 'Personal';
other.watch_ids = {16781314};
assert(p:load('Healer', other));
assert(other.style.font_size == 21 and other.panels.self_buffs.x == 301);
assert(other.window.x == 88 and other.job_profiles['2'] == 'Personal' and other.job_profiles['1'] == nil);
assert(other.shared_layout == false and other.preview == false and other.active_profile == 'Healer');
assert(#other.watch_ids == 1 and other.watch_ids[1] == 16781314, 'A profile must not restore old zone entity IDs.');
other.style.font_size = 15;
assert(p:load('Healer', other) and other.style.font_size == 21);
assert(p:link(other, 3, 'Healer') and other.job_profiles['3'] == 'Healer');
assert(not p:link(other, 3, 'Missing') and other.job_profiles['3'] == 'Healer');
assert(p:link(other, 3, '') and other.job_profiles['3'] == nil);
assert(not p:link(other, 99, 'Healer'));
settings.panels.self_buffs.enabled = false;
settings.panels.self_buffs.x = 333;
settings.party_ui.effects.growth = 'left';
settings.panels.self_buffs.growth = 'left';
other.party_ui.effects.icon_size = 41;
other.party_ui.effects.include = {33};
assert(p:save_layout(settings));
local enabled = other.panels.self_buffs.enabled;
assert(p:load_layout(other));
assert(other.panels.self_buffs.x == 333 and other.panels.self_buffs.enabled == enabled);
assert(other.style.font_size == 21 and other.window.x == 88);
assert(other.party_ui.effects.growth == 'left' and other.panels.self_buffs.growth == 'left',
    'Shared placement keeps the same growth direction on every effect display.');
assert(other.party_ui.effects.icon_size == 41 and other.party_ui.effects.include[1] == 33,
    'Sharing effect placement preserves personal icon sizes and filters.');
MOCK.file_replace_error = true;
assert(not p:delete('Healer'));
assert(#p:list() == 2);
MOCK.file_replace_error = false;
assert(p:delete('Tank') and #p:list() == 1);
local file = assert(io.open(p.path, 'wb')); file:write('broken JSON'); file:close();
local names, problem = p:list();
assert(#names == 0 and type(problem) == 'string');
assert(not p:save_new('Keep file', settings));
assert(not p:delete('Healer'));
assert(not p:load('Healer', other));
file = assert(io.open(p.path, 'rb')); assert(file:read('*a') == 'broken JSON'); file:close();
return true;
